// Builds js/start-map.js: the Woodbridge cloverleaf (US 1/9 × NJ 35, Woodbridge, New Jersey) as drawn
// in OpenStreetMap, for the «Fondo» start circle. Nothing is fetched here; the input is an OSM API
// extract saved by hand from
//   https://api.openstreetmap.org/api/0.6/map?bbox=-74.2972,40.5683,-74.2882,40.5751
// Usage: node prototype/tools/build-start-map.cjs <map.osm>
// Map data © OpenStreetMap contributors, ODbL 1.0. Only the major roads are kept, north up.
const fs = require('fs');
const path = require('path');

const CENTER = [40.5717, -74.2927];
const RADIUS_M = 170;
const KEEP = /^(motorway|trunk|primary|secondary)(_link)?$/;
// Stroke widths in viewBox units (circle = 100). Thinner layers are drawn first.
const WIDTH = (hw) => (hw.endsWith('_link') ? 1.15 : hw === 'trunk' || hw === 'motorway' ? 1.5 : 1.2);

const xml = fs.readFileSync(process.argv[2], 'utf8');
const attr = (tag, k) => (tag.match(new RegExp(`\\b${k}="([^"]*)"`)) || [])[1];
const nodes = new Map();
for (const [tag] of xml.matchAll(/<node\b[^>]*>/g)) nodes.set(attr(tag, 'id'), [Number(attr(tag, 'lat')), Number(attr(tag, 'lon'))]);

// Local equirectangular projection: at this size the error is far below a pixel.
const kx = Math.cos(CENTER[0] * Math.PI / 180) * 111320;
const ky = 110540;
const s = 50 / RADIUS_M;
const xy = ([lat, lon]) => [50 + (lon - CENTER[1]) * kx * s, 50 - (lat - CENTER[0]) * ky * s];

// Distance from the circle's centre to a segment; segments that never come near the circle are dropped.
function reach([ax, ay], [bx, by]) {
  const dx = bx - ax, dy = by - ay;
  const t = Math.max(0, Math.min(1, ((50 - ax) * dx + (50 - ay) * dy) / (dx * dx + dy * dy || 1)));
  return Math.hypot(ax + t * dx - 50, ay + t * dy - 50);
}

const layers = new Map();
let ways = 0;
for (const [, open, body] of xml.matchAll(/<way\b([^>]*)>([\s\S]*?)<\/way>/g)) {
  const hw = (body.match(/<tag k="highway" v="([^"]*)"/) || [])[1];
  if (!hw || !KEEP.test(hw)) continue;
  ways++;
  const pts = [...body.matchAll(/<nd ref="([^"]*)"/g)].map(([, ref]) => nodes.get(ref)).filter(Boolean).map(xy);
  let run = [];
  const flush = () => {
    if (run.length > 1) {
      const w = WIDTH(hw);
      layers.set(w, (layers.get(w) || '') + 'M' + run.map((p) => p.map((n) => n.toFixed(1)).join(',')).join('L'));
    }
    run = [];
  };
  for (let i = 0; i + 1 < pts.length; i++) {
    if (reach(pts[i], pts[i + 1]) > 52) { flush(); continue; }
    if (!run.length) run.push(pts[i]);
    run.push(pts[i + 1]);
  }
  flush();
}

const LAYERS = [...layers].sort(([a], [b]) => a - b);
const out = `// Generated by tools/build-start-map.cjs from OpenStreetMap data (${ways} ways); do not edit by hand.
// Woodbridge cloverleaf, US 1/9 × NJ 35, Woodbridge, New Jersey. Map data © OpenStreetMap contributors, ODbL 1.0.
(function () {
  const LAYERS = ${JSON.stringify(LAYERS)};
  const svg = '<svg viewBox="0 0 100 100" focusable="false" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">'
    + LAYERS.map(([w, d]) => \`<path stroke-width="\${w}" d="\${d}"/>\`).join('') + '</svg>';
  window.E = window.E || {};
  window.E.startMap = () => \`<span class="start-map" aria-hidden="true">\${svg}</span>\`;
})();
`;
fs.writeFileSync(path.resolve(__dirname, '..', 'js', 'start-map.js'), out);
console.log(`start-map.js: ${ways} ways, ${LAYERS.length} layers, ${out.length} bytes`);
