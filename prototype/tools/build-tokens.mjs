// Generates prototype/css/tokens.css from prototype/design-tokens.json.
// Usage: node prototype/tools/build-tokens.mjs [--check]
// --check fails if the committed CSS is stale or V0 drifts from TOKENS-BASE.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'design-tokens.json'), 'utf8'));
const reference = JSON.parse(readFileSync(join(root, '..', 'TOKENS-BASE.json'), 'utf8'));
const outPath = join(root, 'css', 'tokens.css');
const jsOutPath = join(root, 'js', 'families.generated.js');

const PX_GROUPS = new Set(['space', 'radius', 'stroke', 'control']);
const SCALED_GROUPS = new Set(['size']);
const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const isThemed = (v) => v && typeof v === 'object' && 'light' in v && 'dark' in v;

function cssValue(group, value) {
  if (typeof value === 'number') {
    if (SCALED_GROUPS.has(group)) return `calc(${value}px * var(--text-scale, 1))`;
    if (PX_GROUPS.has(group)) return `${value}px`;
    return String(value);
  }
  return value;
}

// Returns { plain: [[name, value]], light: [...], dark: [...] }
function collect(groups) {
  const out = { plain: [], light: [], dark: [] };
  for (const [group, entries] of Object.entries(groups)) {
    for (const [key, value] of Object.entries(entries)) {
      if (key.startsWith('$')) continue;
      const name = `--${kebab(group)}-${kebab(key)}`;
      if (isThemed(value)) {
        out.light.push([name, cssValue(group, value.light)]);
        out.dark.push([name, cssValue(group, value.dark)]);
      } else {
        out.plain.push([name, cssValue(group, value)]);
      }
    }
  }
  return out;
}

const block = (selector, decls) =>
  decls.length ? `${selector} {\n${decls.map(([n, v]) => `  ${n}: ${v};`).join('\n')}\n}\n` : '';

const errors = [];
let css = '/* GENERATED by tools/build-tokens.mjs from design-tokens.json. Do not edit by hand. */\n\n';
const base = collect(tokens.base);
css += block('.app', [...base.plain, ...base.light]);
css += block('.app[data-theme="dark"]', base.dark);

for (const [id, fam] of Object.entries(tokens.families)) {
  const o = collect(fam.override || {});
  for (const [group, entries] of Object.entries(fam.override || {})) {
    for (const [key, value] of Object.entries(entries)) {
      if (!(key in (tokens.base[group] || {}))) errors.push(`${id}: override ${group}.${key} has no base role`);
      if (group === 'color' && !isThemed(value)) errors.push(`${id}: color.${key} must define light and dark`);
    }
  }
  css += `\n/* ${fam.name.en} */\n`;
  css += block(`.app[data-family="${id}"]`, [...o.plain, ...o.light]);
  css += block(`.app[data-family="${id}"][data-theme="dark"]`, o.dark);
}

// V0 must keep the reference values for every role that cites a source color.
const toHex = (c) => '#' + ['red', 'green', 'blue']
  .map((k) => Math.round(parseFloat(c.components[k]) * 255).toString(16).padStart(2, '0')).join('').toUpperCase();
for (const [role, value] of Object.entries(tokens.base.color)) {
  const src = value.$from;
  if (!src || !reference.colors[src]) continue;
  for (const mode of ['light', 'dark']) {
    const want = toHex(reference.colors[src][mode]);
    if (value[mode].toUpperCase() !== want) errors.push(`base.color.${role}.${mode} = ${value[mode]} but ${src} = ${want}`);
  }
}

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

// Composition flags and names are exposed to the classic scripts (file:// cannot fetch JSON).
const families = Object.fromEntries(Object.entries(tokens.families)
  .map(([id, f]) => [id, { id, name: f.name, summary: f.summary, composition: f.composition }]));
const js = '// GENERATED by tools/build-tokens.mjs from design-tokens.json. Do not edit by hand.\n' +
  `window.EARNLY_FAMILIES = ${JSON.stringify(families, null, 2)};\n`;

if (process.argv.includes('--check')) {
  if (readFileSync(outPath, 'utf8') !== css || readFileSync(jsOutPath, 'utf8') !== js) {
    console.error('generated token files are stale: run node prototype/tools/build-tokens.mjs');
    process.exit(1);
  }
  console.log('tokens ok');
} else {
  writeFileSync(outPath, css);
  writeFileSync(jsOutPath, js);
  console.log(`wrote ${outPath} and ${jsOutPath}`);
}
